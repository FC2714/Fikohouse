def validate_lang(lang):
    """Validate and return language code, default to 'en'"""
    valid_langs = ['en', 'de', 'ru', 'az']
    return lang if lang in valid_langs else 'en'

def get_t(lang):
    """Return translation function for given language"""
    lang = validate_lang(lang)
    def t(key):
        return TRANSLATIONS.get(lang, {}).get(key, f'[{key}]')
    return t

def language_selector_html(current_lang):
    """Generate language selector dropdown HTML"""
    current_lang = validate_lang(current_lang)
    languages = [
        ('en', '🇬🇧 English'),
        ('de', '🇩🇪 Deutsch'),
        ('ru', '🇷🇺 Русский'),
        ('az', '🇦🇿 Azərbaycanca')
    ]

    options = "".join([
        f'<option value="{lang_code}" {"selected" if lang_code == current_lang else ""}>{lang_name}</option>'
        for lang_code, lang_name in languages
    ])

    return f'''
    <div class="fixed top-6 right-6 z-50">
        <select id="langSelect" onchange="window.location.href=window.location.pathname + '?lang=' + this.value" class="bg-emerald-600 hover:bg-emerald-700 text-white font-semibold py-2 px-4 rounded-lg cursor-pointer border-0 outline-none">
            {options}
        </select>
    </div>
    '''

def language_selector_html_post(current_lang, email):
    """Generate language selector dropdown HTML for POST pages (like load-mails) that includes email"""
    current_lang = validate_lang(current_lang)
    languages = [
        ('en', '🇬🇧 English'),
        ('de', '🇩🇪 Deutsch'),
        ('ru', '🇷🇺 Русский'),
        ('az', '🇦🇿 Azərbaycanca')
    ]

    options = "".join([
        f'<option value="{lang_code}" {"selected" if lang_code == current_lang else ""}>{lang_name}</option>'
        for lang_code, lang_name in languages
    ])

    return f'''
    <div class="fixed top-6 right-6 z-50">
        <select id="langSelect" onchange="
            const form = document.createElement('form');
            form.method = 'POST';
            form.action = '/load-mails?lang=' + this.value;
            const emailInput = document.createElement('input');
            emailInput.type = 'hidden';
            emailInput.name = 'email_input';
            emailInput.value = '{email}';
            const langInput = document.createElement('input');
            langInput.type = 'hidden';
            langInput.name = 'lang';
            langInput.value = this.value;
            form.appendChild(emailInput);
            form.appendChild(langInput);
            document.body.appendChild(form);
            form.submit();
        " class="bg-emerald-600 hover:bg-emerald-700 text-white font-semibold py-2 px-4 rounded-lg cursor-pointer border-0 outline-none">
            {options}
        </select>
    </div>
    '''
